/// Format `card_critical_high_sub`: "{critical} Nguy cấp • {high} Rủi ro cao" / "{critical} Critical • {high} High Risk"
pub fn format_critical_high_sub(critical: usize, high: usize, lang: Language) -> String {
    match lang {
        Language::Vi => format!("{critical} Nguy cấp • {high} Rủi ro cao"),
        Language::En => format!("{critical} Critical • {high} High Risk"),
    }
}

/// Format `api_key_label`: "Nhập API Key {provider}" / "Enter {provider} API Key"
pub fn format_api_key_label(provider: &str, lang: Language) -> String {
    match lang {
        Language::Vi => format!("Nhập API Key {provider}"),
        Language::En => format!("Enter {provider} API Key"),
    }
}


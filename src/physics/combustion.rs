use crate::physics::models::{CoolFlameResult, FlightMaterial, RiskTier, SfrsAssessment};

/// Microgravity combustion kinetics calculations matching Bebo Ignis-0G formulas.
pub struct CombustionEngine;

impl CombustionEngine {
    /// Calculate Effective Minimum Oxygen Concentration (MOC_eff) with buoyancy,
    /// radiative quenching, aerodynamic blowoff, and ambient pressure adjustments.
    pub fn calculate_effective_moc(
        material: &FlightMaterial,
        gravity_g: f64,
        airflow_cm_s: f64,
        pressure_kpa: f64,
    ) -> f64 {
        let moc_1g = material.moc_1g;
        let moc_ug = material.moc_microg;

        // Buoyant velocity generated by natural convection: 25.0 * sqrt(max(0, g))
        let v_buoyant = 25.0 * gravity_g.max(0.0).sqrt();
        let v_eff = (airflow_cm_s.powi(2) + v_buoyant.powi(2)).sqrt();

        // Radiative quenching penalty under stagnant/low convective flow (< 3.5 cm/s)
        let delta_quench = if v_eff < 3.5 {
            5.0 * (1.0 - (v_eff / 3.5)).powf(1.5)
        } else {
            0.0
        };

        // Convective blowoff penalty at high airflow velocities (> 25.0 cm/s)
        let delta_blowoff = if v_eff > 25.0 {
            0.16 * (v_eff - 25.0).powf(1.2)
        } else {
            0.0
        };

        // Pressure adjustment scaling relative to standard atmospheric pressure (101.3 kPa)
        let p_ratio = (pressure_kpa / 101.3).max(0.1);
        let delta_pressure = 1.8 * (1.0 - p_ratio.powf(0.35));

        // Gravity interpolation factor clamped between 0.0 (micro-g) and 1.0 (terrestrial)
        let g_factor = gravity_g.max(0.0).sqrt().clamp(0.0, 1.0);
        let base_moc = moc_ug + (moc_1g - moc_ug) * g_factor;

        let effective_moc = base_moc + delta_quench + delta_blowoff + delta_pressure;
        effective_moc.clamp(8.0, 60.0)
    }

    /// Calculate flame spread rate (mm/s) taking into account the low-flow
    /// microgravity ventilation paradox peaking at v = 12 cm/s.
    pub fn calculate_flame_spread_rate(
        material: &FlightMaterial,
        gravity_g: f64,
        oxygen_pct: f64,
        pressure_kpa: f64,
        airflow_cm_s: f64,
        effective_moc: f64,
    ) -> f64 {
        if oxygen_pct < effective_moc {
            return 0.0;
        }

        let base_spread = material.base_spread_rate_mm_s;

        let o2_margin = (oxygen_pct - effective_moc).max(0.01);
        let o2_ref_span = (material.moc_microg * 0.3).max(4.0);
        let o2_scale = (o2_margin / o2_ref_span).powf(1.15);

        let p_scale = (pressure_kpa / 101.3).max(0.1).sqrt();

        let v_b = 25.0 * gravity_g.max(0.0).sqrt();
        let v_total = (airflow_cm_s.powi(2) + v_b.powi(2)).sqrt();

        // Ventilation factor: Microgravity Low-Flow Paradox peaking at 12 cm/s when g < 0.1
        let vent_factor = if gravity_g < 0.1 {
            0.35 + 1.35 * (v_total / 12.0) * (1.0 - (v_total / 12.0)).exp()
        } else {
            0.70 + 0.50 * (v_total / 25.0).powf(0.85)
        };

        let spread_rate = base_spread * o2_scale * p_scale * vent_factor;
        spread_rate.max(0.0)
    }

    /// Calculate Space Fire Risk Score (0–100) and classify into threat tier.
    pub fn calculate_space_fire_risk_score(
        material: &FlightMaterial,
        effective_moc: f64,
        spread_rate: f64,
        oxygen_pct: f64,
        _pressure_kpa: f64,
        _airflow_cm_s: f64,
    ) -> SfrsAssessment {
        if oxygen_pct < effective_moc {
            return SfrsAssessment {
                score: 0.0,
                tier: RiskTier::Safe,
                color_code: "#10B981".to_string(),
                score_o2: 0.0,
                score_spread: 0.0,
                score_energy: 0.0,
                penalty_cabin: 0.0,
            };
        }

        let o2_overage = oxygen_pct - effective_moc;
        let hoc = material.heat_of_combustion_mj_kg;

        let score_o2 = (o2_overage * 2.8).min(35.0);
        let score_spread = (spread_rate * 20.0).min(35.0);
        let score_energy = ((hoc / 45.0) * 15.0).min(15.0);
        let penalty_cabin = 15.0 * ((oxygen_pct - 21.0) / 19.0).max(0.0);

        let raw_sfrs = score_o2 + score_spread + score_energy + penalty_cabin;
        let sfrs = raw_sfrs.clamp(5.0, 100.0);

        let (tier, color_code) = if sfrs >= 70.0 {
            (RiskTier::Critical, "#E03C31")
        } else if sfrs >= 45.0 {
            (RiskTier::High, "#F59E0B")
        } else if sfrs >= 20.0 {
            (RiskTier::Moderate, "#38BDF8")
        } else {
            (RiskTier::Safe, "#10B981")
        };

        SfrsAssessment {
            score: sfrs,
            tier,
            color_code: color_code.to_string(),
            score_o2,
            score_spread,
            score_energy,
            penalty_cabin,
        }
    }

    /// Detect low-temperature, invisible cool flame transition under microgravity.
    pub fn detect_cool_flames(
        material: &FlightMaterial,
        gravity_g: f64,
        airflow_cm_s: f64,
        oxygen_pct: f64,
        pressure_kpa: f64,
        lang: &str,
        eff_moc: Option<f64>,
    ) -> CoolFlameResult {
        if !material.cool_flame_susceptible {
            let message = if lang == "vi" {
                "Không nhạy cảm với chuyển dịch ngọn lửa lạnh.".to_string()
            } else {
                "Not susceptible to cool flame transition.".to_string()
            };
            return CoolFlameResult {
                active: false,
                message,
            };
        }

        let moc = eff_moc.unwrap_or_else(|| {
            Self::calculate_effective_moc(material, gravity_g, airflow_cm_s, pressure_kpa)
        });

        if gravity_g <= 0.08
            && airflow_cm_s <= 4.0
            && pressure_kpa >= 35.0
            && oxygen_pct >= moc - 2.5
            && oxygen_pct <= moc + 2.0
        {
            let message = if lang == "vi" {
                "CẢNH BÁO NGUY HIỂM: Chế độ Ngọn Lửa Lạnh Đang Hoạt động. Tổn thất nhiệt bức xạ dập tắt vùng phản ứng nhiệt độ cao, đưa nhiên liệu vào quá trình oxy hóa hóa học vô hình, phát xạ thấp (600-800K). Sinh ra nồng độ khí Carbon Monoxide (CO) và formaldehyde kịch độc mà không phát ra ánh sáng cảnh báo cho phi hành đoàn.".to_string()
            } else {
                "CRITICAL ALERT: Cool Flames Regime Active. Radiative heat loss suppresses the high-temperature reaction zone, transitioning fuel into an invisible, low-luminosity chemical oxidation process (600-800K). Generates high levels of toxic Carbon Monoxide (CO) and formaldehydes without visible crew warning.".to_string()
            };
            CoolFlameResult {
                active: true,
                message,
            }
        } else {
            let message = if lang == "vi" {
                "Chế độ đốt cháy tiêu chuẩn hoặc đã dập tắt.".to_string()
            } else {
                "Standard combustion regime or quenched.".to_string()
            };
            CoolFlameResult {
                active: false,
                message,
            }
        }
    }

    /// Generate 60-point velocity sweep (0 to 50 cm/s) for flammability boundary map.
    pub fn generate_extinction_curve(
        material: &FlightMaterial,
        gravity_g: f64,
        pressure_kpa: f64,
    ) -> (Vec<f64>, Vec<f64>) {
        let count = 60;
        let mut v_sweep = Vec::with_capacity(count);
        let mut moc_sweep = Vec::with_capacity(count);

        let step = 50.0 / (count as f64 - 1.0);
        for i in 0..count {
            let v = i as f64 * step;
            let moc = Self::calculate_effective_moc(material, gravity_g, v, pressure_kpa);
            v_sweep.push(v);
            moc_sweep.push(moc);
        }

        (v_sweep, moc_sweep)
    }
}
